"""Aggregates documentation/asset_manifest_parts/*.md into documentation/ASSET_MANIFEST.md.

Run:  py -3 -P tools/docs/build_asset_manifest.py
Each production area owns its part file; this script only adds the index, the lead's own entries and the
provenance rules, so the manifest never drifts from the parts.
"""
import os
import glob

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PARTS = os.path.join(ROOT, "documentation", "asset_manifest_parts")
OUT = os.path.join(ROOT, "documentation", "ASSET_MANIFEST.md")
ORDER = ["render-camera", "splash", "prologue", "env_karsk","karsk_skyline", "explore_karsk", "minigames", "minigames_r7_kb", "env_berlin", "explore_berlin",
         "characters", "portraits", "characters_r7", "portraits_r7", "great_hall", "parade", "env_plaza", "explore_plaza", "plaza_polish",
         "trans_a1m1", "trans_finale", "c3", "env_veltrava_station", "env_veltrava_hall", "c3_cine", "minigames_r7_v", "minigames_r7_relay",
         "tasks", "memories", "c3p2_story", "env_c3p2_archive", "env_c3p2_night", "c3p2_cine", "pixel_fire", "c3p2_puzzle",
         "c3p2_cast_audio", "explore_c3p2", "feel_r8", "c4_story", "env_c4_tunnels",
         "env_c4_annex", "c4_cine", "c4_puzzle", "c4_cast_audio", "explore_c4", "board", "feel_r9",
         "env_c4p2_karsk", "env_c4p2_berlin", "c4p2_cine", "c4p2_puzzle", "c4p2_cast_audio", "explore_c4p2", "polish_r10", "ui", "explore_system", "photo_mode", "credits", "audio", "story"]

HEADER = """# ASSET MANIFEST — Ashes of Empires: The Last Winter

Generated by `tools/docs/build_asset_manifest.py` from `documentation/asset_manifest_parts/`. Do not edit by hand;
edit the part of the owning area and re-run the script.

## Provenance rules (apply to every entry)
- **All art, audio, music, text and code are original work created for this project** by its generator scripts
  (`tools/pixelgen/*`, `tools/audiogen/*`) or written by hand. Every generator is deterministic: re-running it
  reproduces the files byte-for-byte.
- **The only third-party assets are four font families under the SIL Open Font License 1.1** (PT Serif, Oswald,
  Courier Prime, PT Mono — downloaded from the official google/fonts repository; licence texts ship next to them).
  See the UI part below for URLs and hashes.
- **No sample, texture, sound or image from the internet or from the reference images was copied, traced or
  embedded.** `documentation/references/` is an internal style study only, excluded from git and from the build.
- No purchased assets, no subscriptions, no AI-generated media from external services.
- The Great Hall and the "Reichssiegel" are fictional. Real regime insignia (swastika, state eagle, hammer & sickle,
  red star) exist only as `*_hist` variants of in-world assets, shown while the setting "Historische Hoheitszeichen"
  is on (TECHNICAL_ARCHITECTURE §12.4, StGB §86 Abs. 4 social-adequacy context); every one has a neutral twin.
- Real-history cards (`data/explore/history_*.json`, `data/locale/de_history_*.json`) are original German texts
  written from the sources listed on each card; they were researched and then independently fact-checked.

## Lead / integration entries
| Path | What | How it was made |
|---|---|---|
| `tools/pixelgen/pg.py` | shared pixel-art library (palettes, Bayer dither, layers with height→normal maps, volumetric puffs) | hand-written Python |
| `data/palettes.json`, `data/grades.json` | palettes and colour-grade presets | exported from `pg.PALETTES` / hand-authored |
| `assets/shaders/post_grade.gdshader` | post chain: palette snap (Bayer) → lift/gamma/gain → vignette → grain → fade | hand-written GLSL |
| `assets/icon/icon.png`, `icon_32.png`, `icon.ico` | window and executable icon (dome, stamp ring, one warm window) | `tools/pixelgen/icon.py` |
| `assets/environments/_test/*` | pipeline test environment (not shipped) | `tools/pixelgen/env_test.py` |

## Index
"""


def main():
    names = [os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(PARTS, "*.md"))]
    names.sort(key=lambda n: (ORDER.index(n) if n in ORDER else 99, n))
    out = [HEADER]
    for n in names:
        out.append("- [%s](#part-%s)\n" % (n, n))
    for n in names:
        with open(os.path.join(PARTS, n + ".md"), encoding="utf-8") as f:
            body = f.read().strip()
        # demote the part's own headings by one level so the document keeps a single H1
        lines = []
        for line in body.splitlines():
            lines.append("#" + line if line.startswith("#") else line)
        out.append("\n\n---\n<a id=\"part-%s\"></a>\n\n" % n)
        out.append("\n".join(lines))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out) + "\n")
    print("wrote", OUT, "from", len(names), "parts")


if __name__ == "__main__":
    main()
