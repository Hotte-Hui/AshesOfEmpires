def c(h, a=255):
    return hx(h, a)


def L(w, h):
    return pg.Layer(w, h)


def dither_fill(l, mask, x0, y0, tone, ramp):
    cols = np.stack([c(h) for h in ramp])
    n = len(ramp)
    t = np.clip(tone, 0, n - 1)
    fl = np.floor(t)
    idx = fl + ((t - fl) > pg.bayer(mask.shape[1], mask.shape[0], x0, y0))
    idx = np.clip(idx, 0, n - 1).astype(np.int32)
    l._put(mask, x0, y0, cols[idx])


# ============================================================================ row strips
def doc_meta(row) -> dict:
    with open(os.path.join(DOCS, row['meta']), encoding='utf-8') as f:
        d = json.load(f)
    for e in d['documents']:
        if e.get('id') == row['doc']:
            return e
    raise KeyError(row['doc'])


def strip_map(row):
    """[(src_rect, (dst_x, dst_y))] -- where each source strip lands in the composed image (1 px mount
    outline around, 1 px seam between strips).  Default: stacked top to bottom."""
    out = []
    if row.get('place'):
        for s, at in zip(row['strips'], row['place']):
            out.append((s, (int(at[0]), int(at[1]))))
    else:
        y = 1
        for s in row['strips']:
            out.append((s, (1, y)))
            y += s[3] + 1
    w = max(at[0] + s[2] for s, at in out) + 1
    h = max(at[1] + s[3] for s, at in out) + 1
    return out, w, h


def to_strip(row, rect):
    """Document rect -> rect in strip coordinates (the source strip that contains its centre)."""
    mp, _, _ = strip_map(row)
    cx, cy = rect[0] + rect[2] / 2.0, rect[1] + rect[3] / 2.0
    for (sx, sy, sw, sh), (dx, dy) in mp:
        if sy <= cy < sy + sh and sx <= cx < sx + sw:
            return [rect[0] - sx + dx, rect[1] - sy + dy, rect[2], rect[3]]
    raise ValueError('rect %s outside the strips of %s' % (rect, row['id']))


def first_word(doc_img: np.ndarray, rect, text: str = '') -> list:
    """Extent of the first word of a pixel-lettered line: ink columns up to the first gap >= 3 columns,
    capped by the share of the first word in the line's text (a stamp may touch the line)."""
    x, y, w, h = rect
    reg = doc_img[y:y + h, x:x + w, :3].astype(np.int32)
    bg = np.median(reg.reshape(-1, 3), axis=0)
    ink = (np.abs(reg - bg).sum(axis=2) > 90).any(axis=0)
    xs = np.nonzero(ink)[0]
    if xs.size == 0:
        return list(rect)
    start, end, gap = int(xs[0]), int(xs[0]), 0
    for i in range(start, w):
        if ink[i]:
            end, gap = i, 0
        else:
            gap += 1
            if gap >= 3:
                break
    if text:
        word = text.split(' ')[0]
        cap = start + int(round(w * len(word) / max(1, len(text)))) + 1
        end = min(end, cap)
    return [x + start, y, end - start + 1, h]


def dash_extent(doc_img: np.ndarray, rect) -> list:
    """The printed dash of an empty table cell (darkest horizontal run inside rect)."""
    x, y, w, h = rect
    reg = doc_img[y:y + h, x:x + w, :3].astype(np.int32).sum(axis=2)
    row = int(np.argmin(reg.min(axis=1)))
    thr = reg[row].min() + 60
    xs = np.nonzero(reg[row] <= thr)[0]
    return [x + int(xs[0]), y + row, int(xs[-1] - xs[0] + 1), 1]


def row_strip(row):
    """Thumbnail strip of one paper + the resolved mark rects (strip coordinates)."""
    meta = doc_meta(row)
    src = np.array(Image.open(os.path.join(DOCS, row['doc'] + '.png')).convert('RGBA'))
    mp, w, h = strip_map(row)
    l = L(w, h)
    l.rect(0, 0, w, h, c(NIGHT))                               # mount outline + seams between cut strips
    for (sx, sy, sw, sh), (dx, dy) in mp:
        l.c[dy:dy + sh, dx:dx + sw] = src[sy:sy + sh, sx:sx + sw]
    # photo corners holding the clipping (slate card, 1 px light edge)
    for (x0, y0, fx, fy) in ((1, 1, 1, 1), (w - 2, 1, -1, 1), (1, h - 2, 1, -1), (w - 2, h - 2, -1, -1)):
        for k in range(4):
            for j in range(4 - k):
                l.px(x0 + fx * j, y0 + fy * k, c(SLATE[1]))
        l.px(x0 + fx * 3, y0, c(SLATE[3])); l.px(x0, y0 + fy * 3, c(SLATE[3]))
    marks = []
    for kind, key, field in row['marks']:
        m = meta['marks'][key]
        r = m[field]
        if kind == 'word':
            r = first_word(src, r, str(m.get('text', '')))
        elif kind == 'dash':
            r = dash_extent(src, r)
        marks.append({'kind': kind, 'source': key, 'doc_rect': list(map(int, r)), 'rect': to_strip(row, r)})
    return l, marks, meta


# ============================================================================ pencil marks
def _stroke(l, pts, col, col_d, rng, light=0.0):
    """Connected 1 px pencil stroke through pts; a few pixels in the darker (pressure) tone."""
    prev = None
    for (x, y) in pts:
        p = (int(round(x)), int(round(y)))
        if prev is not None and p != prev:
            l.line(prev[0], prev[1], p[0], p[1], c(col_d if rng.random() < 0.18 else col))
        elif prev is None:
            l.px(p[0], p[1], c(col))
        prev = p
    if light > 0:
        for (x, y) in pts[::7]:
            if rng.random() < light:
                l.px(int(round(x)), int(round(y)), CLEAR)


def pencil_loop(l, rect, col, col_d, seed, pad=2.6):
    """A quick hand loop around rect: a bit more than one turn, the end overshoots the start."""
    x, y, w, h = rect
    rng = np.random.default_rng(seed)
    cx, cy = x + (w - 1) / 2.0, y + (h - 1) / 2.0
    rx, ry = w / 2.0 + pad, h / 2.0 + pad - 0.4
    t0 = rng.uniform(-2.6, -2.0)
    turns = 1.14
    n = int((rx + ry) * 8 + 40)
    pts = []
    for i in range(n + 1):
        f = i / n
        t = t0 + 2 * math.pi * turns * f
        wob = 1.0 + 0.05 * math.sin(3 * t + seed) + 0.07 * f
        pts.append((cx + rx * wob * math.cos(t), cy + ry * wob * math.sin(t) - 0.8 * f))
    _stroke(l, pts, col, col_d, rng)


def pencil_underline(l, rect, col, col_d, seed):
    x, y, w, h = rect
    rng = np.random.default_rng(seed)
    yb = y + h + 1
    pts = [(x - 1 + i, yb + 0.45 * math.sin(i / 6.0 + seed)) for i in range(w + 3)]
    _stroke(l, pts, col, col_d, rng)
    # a short second pass under the start of the word (pressure)
    _stroke(l, [(x + i, yb + 1) for i in range(min(w, 9))], col_d, col_d, rng)


def pencil_tick(l, rect, col, col_d):
    """Check mark right of a symbol (counting the wagons: 1, 2, 3)."""
    x, y, w, h = rect
    x0, yb = x + w + 1, y + h - 2
    for i, (dx, dy) in enumerate(((0, -2), (1, -1), (2, 0), (3, -1), (4, -2), (5, -3), (6, -4), (7, -5))):
        l.px(x0 + dx, yb + dy, c(col_d if i in (2, 3) else col))
    l.px(x0 + 2, yb + 1, c(col))


def mark_layer(row, strip_l, marks):
    l = L(strip_l.w, strip_l.h)
    col, col_d = (RED, RED_D) if row['ink'] == 'red' else (AMBER, COPPER_L)
    seed = sum(map(ord, row['id']))
    for i, m in enumerate(marks):
        if m['kind'] == 'loop':
            pencil_loop(l, m['rect'], col, col_d, seed + 17 * i)
        elif m['kind'] == 'dash':
            pencil_loop(l, m['rect'], col, col_d, seed + 17 * i, pad=2.2)
        elif m['kind'] == 'tick':
            pencil_tick(l, m['rect'], col, col_d)
        else:
            pencil_underline(l, m['rect'], col, col_d, seed + 17 * i)
    # never paint onto the mount outline: marks stay on the paper
    l.c[0, :] = CLEAR
    l.c[-1, :] = CLEAR
    l.c[:, 0] = CLEAR
    l.c[:, -1] = CLEAR
    return l


# ============================================================================ cards / slot / brace
def glyph_mask(shape: str, s: int = 11) -> np.ndarray:
    yy, xx = np.mgrid[0:s, 0:s].astype(np.float32)
    cc = (s - 1) / 2.0
    dx, dy = xx - cc, yy - cc
    r = np.sqrt(dx * dx + dy * dy)
    if shape == 'ring':
        return (r <= s / 2.0 - 0.15) & (r >= s / 2.0 - 2.6)
    if shape == 'cross':
        return (np.abs(dx) <= 1.2) | (np.abs(dy) <= 1.2)
    if shape == 'star':           # four-point star: concave diamond
        return np.sqrt(np.abs(dx)) + np.sqrt(np.abs(dy)) <= math.sqrt(cc) + 0.35
    if shape == 'bowtie':         # two triangles touching at the centre (left / right)
        return (np.abs(dy) <= np.abs(dx) * 0.95 + 0.5) & (np.abs(dx) <= cc)
    raise ValueError(shape)


def card(card_id: str) -> pg.Layer:
    """Registry index card (Karteikarte) of the commission, series C-17: cream face, red series edge on
    top, glyph box at the left, text field (HD text from the UI)."""
    w, h = CARD_W, CARD_H
    l = L(w, h)
    seed = sum(map(ord, card_id)) * 7
    rng = np.random.default_rng(seed)
    edge = c(NIGHT)
    l.rect(1, 0, w - 2, h, edge)
    l.rect(0, 1, w, h - 2, edge)
    yy, xx = np.mgrid[0:h - 2, 0:w - 2].astype(np.float32)
    tone = 4.05 + (pg.value_noise(w - 2, h - 2, 24, seed, octaves=2) - 0.5) * 0.22
    e = np.minimum(np.minimum(xx, w - 3 - xx), np.minimum(yy, h - 3 - yy))
    tone -= np.clip((3 - e) / 3, 0, 1) * 0.55
    dither_fill(l, np.ones((h - 2, w - 2), bool), 1, 1, tone, PAPER)
    l.rect(1, 1, w - 2, 1, c(RED))                              # series edge (registry colour of C-17)
    l.rect(2, 2, w - 4, 1, c(RED_D))
    l.rect(1, h - 3, w - 2, 1, c(PAPER[3]))                     # bottom shading
    l.rect(1, h - 2, w - 2, 1, c(PAPER[2]))
    gx, gy, gw, gh = GLYPH_BOX
    l.rect(gx, gy, gw, gh, c(PAPER[5]))
    for x in range(gx, gx + gw):
        l.px(x, gy, c(PAPER[2])); l.px(x, gy + gh - 1, c(PAPER[2]))
    for y in range(gy, gy + gh):
        l.px(gx, y, c(PAPER[2])); l.px(gx + gw - 1, y, c(PAPER[2]))
    for px_, py_ in ((gx, gy), (gx + gw - 1, gy), (gx, gy + gh - 1), (gx + gw - 1, gy + gh - 1)):
        l.px(px_, py_, c(PAPER[5]))
    l._put(glyph_mask(CARD_GLYPH[card_id], 11), gx + 2, gy + 2, c(INK))
    l.rect(gx + gw + 1, 6, 1, h - 11, c(PAPER[3]))              # divider glyph | text
    for _ in range(9):                                          # wear specks, outside the text field
        x = int(rng.integers(2, gx + gw)) if rng.random() < 0.5 else int(rng.integers(w - 6, w - 2))
        y = int(rng.integers(4, h - 4))
        if not (gx <= x < gx + gw and gy <= y < gy + gh):
            l.px(x, y, c(PAPER[3] if rng.random() < 0.6 else PAPER[5]))
    return l


def slot() -> pg.Layer:
    """Empty place of a row: recessed dark field with a dashed rule (same language as c3_slot)."""
    w, h = CARD_W, CARD_H
    l = L(w, h)
    l.rect(1, 1, w - 2, h - 2, c(NIGHT1, 215))
    for x in range(1, w - 1, 3):
        l.px(x, 0, c(WALL[3])); l.px(x + 1, 0, c(WALL[3]))
        l.px(x, h - 1, c(WALL[3])); l.px(x + 1, h - 1, c(WALL[3]))
    for y in range(1, h - 1, 3):
        l.px(0, y, c(WALL[3])); l.px(0, y + 1, c(WALL[3]))
        l.px(w - 1, y, c(WALL[3])); l.px(w - 1, y + 1, c(WALL[3]))
    l.rect(2, 2, w - 4, 1, c(NIGHT, 225))
    # faint card silhouette: where the glyph box of the entry will sit
    gx, gy, gw, gh = GLYPH_BOX
    for x in range(gx, gx + gw, 2):
        l.px(x, gy, c(WALL[1])); l.px(x, gy + gh - 1, c(WALL[1]))
    for y in range(gy, gy + gh, 2):
        l.px(gx, y, c(WALL[1])); l.px(gx + gw - 1, y, c(WALL[1]))
    return l


def bracket(height: int) -> pg.Layer:
    """Red pencil brace „}“ over the four rows: tip in the middle, pointing to the right."""
    w = 13
    l = L(w, height)
    rng = np.random.default_rng(1764)
    mid = (height - 1) / 2.0
    pts_top, pts_bot = [], []
    n = height * 3
    for i in range(n + 1):
        f = i / n                       # 0 at the top end, 1 at the tip
        y = f * mid
        # brace profile: hook at the end (f~0), straight shank, small hook into the tip (f~1)
        if f < 0.08:
            x = 1 + 3.2 * (1 - math.cos(f / 0.08 * math.pi / 2))
        elif f < 0.9:
            x = 4.2 + 0.25 * math.sin((f - 0.08) * 7.0)
        else:
            g = (f - 0.9) / 0.1
            x = 4.2 + 6.8 * math.sin(g * math.pi / 2) ** 2
        pts_top.append((x, y + 0.5))
        pts_bot.append((x, height - 1 - y - 0.5))
    _stroke(l, pts_top, RED, RED_D, rng)
    _stroke(l, pts_bot, RED, RED_D, rng)
    # second, slightly offset pass on the shank (a pencil drawn twice)
    for pts in (pts_top, pts_bot):
        _stroke(l, [(x + 1, y) for (x, y) in pts[int(n * 0.15):int(n * 0.8):2]], RED_D, RED_D, rng, light=0.5)
    return l


# ============================================================================ output
def save_png(layer: pg.Layer, path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    Image.fromarray(layer.c, 'RGBA').save(path)


def rel(path: str) -> str:
    return 'res://' + os.path.relpath(path, ROOT).replace(os.sep, '/')


def surface(layer: pg.Layer, rect) -> str:
    """Median opaque colour inside rect (the background the UI sets text on)."""
    x, y, w, h = rect
    reg = layer.c[y:y + h, x:x + w].reshape(-1, 4)
    reg = reg[reg[:, 3] > 0][:, :3]
    m = np.median(reg, axis=0).astype(int)
    return '#%02X%02X%02X' % tuple(m)


def check_solution():
    pairs = [r['pairs_with'] for r in ROWS]
    assert pairs == SOLUTION, pairs
    pz = json.load(open(os.path.join(ROOT, 'data', 'v3', 'puzzles.json'), encoding='utf-8'))
    p = next(x for x in pz['puzzles'] if x['id'] == 'pz_c3_check')
    assert p['solution'] == SOLUTION, p['solution']
    assert sorted(p['display_symbols']) == sorted(SOLUTION)
    return p['display_symbols']


