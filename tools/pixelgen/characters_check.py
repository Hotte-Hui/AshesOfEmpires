"""characters_check.py -- validates the character sheets against TECHNICAL_ARCHITECTURE section 4 (+ 12.6).

    py -3 -P tools/pixelgen/characters_check.py      -> prints a report, exit code 1 on any failure
Checks: json schema, row/frame layout, non-empty frames, feet on the origin row (idle / talk / walk: one
foot always planted), no clipping at cell borders, normal-map alpha == diffuse alpha, normals normalised and
facing the viewer, figure heights (+-1 px of the round-1 sizes so the sprites still fit the environments),
required rows per role, idle-variant integrity, protagonist walk ground speed (player walks 45 px/s and
scales playback by speed / ground_speed), no orphan pixels (single opaque pixels without a 4-neighbour),
portrait strips (if present; portraits are generated by chargen_portrait*).
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'characters')

EXPECT_H = {  # (min, max) figure height in px incl. headgear, idle_side frame 0
    'alexei': (45, 47), 'konrad': (47, 49), 'irina': (43, 45), 'emil': (43, 45), 'worker_a': (46, 48),
    'babushka': (39, 41), 'child_a': (29, 31), 'berlin_father': (45, 47), 'berlin_mother': (42, 44),
    'berlin_child': (30, 32), 'clerk': (45, 47), 'guard': (47, 49),
    'librarian': (42, 45), 'porter': (45, 48), 'vendor': (42, 45), 'worker_b': (45, 48),
}
CONTRACT_ROWS = ['idle_side', 'walk_side', 'idle_front', 'walk_front', 'idle_back', 'walk_back', 'inspect_side',
                 'interact_side', 'talk_side']
REQUIRED = {'alexei': CONTRACT_ROWS, 'konrad': CONTRACT_ROWS}
NEW_MIN = ['idle_side', 'walk_side', 'talk_side', 'idle_front']
NPC_MIN = {'irina': ['idle_side', 'talk_side'], 'emil': ['idle_side', 'talk_side'],
           'librarian': NEW_MIN, 'porter': NEW_MIN, 'vendor': NEW_MIN, 'worker_b': NEW_MIN,
           'worker_a': ['idle_side', 'walk_side', 'talk_side'], 'babushka': ['idle_side', 'walk_side', 'talk_side']}
CIV_MIN = ['idle_side', 'walk_side']
PROTAG_SPEED = (34.0, 35.5)


def orphans(a: np.ndarray) -> int:
    """Opaque pixels without any 8-neighbour (diagonal 1-px lines are legitimate pixel art)."""
    p = np.pad(a, 1)
    h, w = a.shape
    nb = np.zeros_like(a)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            if dx or dy:
                nb |= p[1 + dy:1 + dy + h, 1 + dx:1 + dx + w]
    return int((a & ~nb).sum())


def main():
    fails, notes = [], []
    # portrait-only speakers (e.g. the plaza photographer) have no sprite sheet
    ids = sorted(d for d in os.listdir(OUT) if os.path.isdir(os.path.join(OUT, d)) and not d.startswith('_')
                 and os.path.exists(os.path.join(OUT, d, 'sheet.json')))
    for cid in ids:
        d = os.path.join(OUT, cid)
        meta = json.load(open(os.path.join(d, 'sheet.json'), encoding='utf-8'))
        for k in ('id', 'cell', 'origin', 'facing', 'anims'):
            if k not in meta:
                fails.append(f'{cid}: sheet.json missing {k}')
        cw, ch = meta['cell']
        ox, oy = meta['origin']
        img = np.asarray(Image.open(os.path.join(d, 'sheet.png')).convert('RGBA'))
        nrm = np.asarray(Image.open(os.path.join(d, 'sheet_n.png')).convert('RGBA'))
        if img.shape != nrm.shape:
            fails.append(f'{cid}: normal map size {nrm.shape} != sheet {img.shape}')
        if not np.array_equal(img[..., 3] > 0, nrm[..., 3] > 0):
            fails.append(f'{cid}: normal alpha differs from diffuse alpha')
        if not np.isin(img[..., 3], (0, 255)).all():
            fails.append(f'{cid}: alpha is not binary')
        hp = os.path.join(d, 'sheet_hist.png')
        if os.path.exists(hp):
            himg = np.asarray(Image.open(hp).convert('RGBA'))
            if himg.shape != img.shape or not np.array_equal(himg[..., 3] > 0, img[..., 3] > 0):
                fails.append(f'{cid}: sheet_hist.png must match sheet.png in size and alpha (shared normal map)')
            elif np.array_equal(himg, img):
                fails.append(f'{cid}: sheet_hist.png is identical to sheet.png')
            notes.append(f'{"":14s} historical-insignia variant sheet_hist.png')
        a = img[..., 3] > 0
        N = nrm[..., :3].astype(np.float32) / 255 * 2 - 1
        ln = np.linalg.norm(N[a], axis=-1)
        if len(ln) and (ln.min() < 0.9 or ln.max() > 1.1):
            fails.append(f'{cid}: normals not unit length ({ln.min():.2f}..{ln.max():.2f})')
        if (N[a][:, 2] < -0.05).any():
            fails.append(f'{cid}: normals pointing away from the viewer')
        names = list(meta['anims'])
        for n_ in REQUIRED.get(cid, []):
            if n_ not in meta['anims']:
                fails.append(f'{cid}: missing contract row {n_}')
        need = NPC_MIN.get(cid, CIV_MIN if cid not in REQUIRED else [])
        for n_ in need:
            if n_ not in meta['anims']:
                fails.append(f'{cid}: missing required anim {n_}')
        rows_used = set()
        n_orph = 0
        for name, an in meta['anims'].items():
            r, nf = an['row'], an['frames']
            if r in rows_used:
                fails.append(f'{cid}: row {r} used twice')
            rows_used.add(r)
            if (r + 1) * ch > img.shape[0] or nf * cw > img.shape[1]:
                fails.append(f'{cid}:{name} outside the sheet')
                continue
            for v in an.get('variants', []):
                if v not in meta['anims']:
                    fails.append(f'{cid}:{name} variant {v} missing')
                elif meta['anims'][v].get('loop', True):
                    fails.append(f'{cid}:{name} variant {v} must not loop')
            for f in range(nf):
                cell = a[r * ch:(r + 1) * ch, f * cw:(f + 1) * cw]
                if not cell.any():
                    fails.append(f'{cid}:{name}[{f}] empty')
                    continue
                n_orph += orphans(cell)
                if cell[:, 0].any() or cell[:, -1].any() or cell[0, :].any():
                    fails.append(f'{cid}:{name}[{f}] touches the cell border (clipped)')
                if cell[oy + 1:, :].any():
                    fails.append(f'{cid}:{name}[{f}] has pixels below the origin row')
                ys, xs = np.nonzero(cell)
                # one foot is always on the origin row -- also in the front / back walks since round 7 (their
                # planted foot used to travel 1-2 px up in depth, which lifted the whole figure mid-stride)
                grounded = name.split('_')[0] in ('idle', 'talk', 'blink', 'look', 'gesture', 'work', 'walk',
                                                  'inspect', 'interact')
                if grounded and 'hop' not in name and ys.max() != oy:
                    # hops / heel rises may lift both feet for a frame: allow 2 px for gesture rows only
                    if not (name.startswith('gesture') and oy - ys.max() <= 2):
                        fails.append(f'{cid}:{name}[{f}] feet row {ys.max()} != origin {oy}')
                if name.startswith('idle') or name.startswith('talk'):
                    foot = xs[ys >= oy - 1]
                    if abs(foot.mean() - ox) > 3.5:
                        fails.append(f'{cid}:{name}[{f}] feet centre {foot.mean():.1f} far from origin x {ox}')
            # empty cells beyond frame count must stay empty
            if a[r * ch:(r + 1) * ch, nf * cw:].any():
                fails.append(f'{cid}:{name} has pixels beyond its frame count')
        if n_orph:
            fails.append(f'{cid}: {n_orph} orphan pixel(s)')
        gs = meta.get('ground_speed', {})
        if cid in REQUIRED:
            w = gs.get('walk_side', 0)
            if not PROTAG_SPEED[0] <= w <= PROTAG_SPEED[1]:
                fails.append(f'{cid}: walk_side ground_speed {w} outside {PROTAG_SPEED}')
        r0 = meta['anims']['idle_side']['row']
        cell = a[r0 * ch:(r0 + 1) * ch, 0:cw]
        ys = np.nonzero(cell)[0]
        hgt = oy - ys.min() + 1
        lo, hi = EXPECT_H.get(cid, (20, 56))
        notes.append(f'{cid:14s} height {hgt:2d}px rows={len(names):2d} sheet={img.shape[1]}x{img.shape[0]}'
                     f' walk={gs.get("walk_side", "-")}')
        if not lo <= hgt <= hi:
            fails.append(f'{cid}: figure height {hgt} outside {lo}-{hi}')
        pp = os.path.join(d, 'portrait.png')
        if os.path.exists(pp) and os.path.exists(os.path.join(d, 'portrait.json')):
            pj = json.load(open(os.path.join(d, 'portrait.json'), encoding='utf-8'))
            pim = Image.open(pp)
            n = len(pj['expressions'])
            if pim.size != (pj['size'][0] * n, pj['size'][1]):
                fails.append(f'{cid}: portrait strip {pim.size} != {n} x {pj["size"]}')
            notes.append(f'{"":14s} portrait {pim.size[0]}x{pim.size[1]} {pj["expressions"]}')
    for n in notes:
        print(n)
    if fails:
        print('\nFAIL')
        for f in fails:
            print('  -', f)
        return 1
    print(f'\nOK: all {len(ids)} character sheets pass')
    return 0


if __name__ == '__main__':
    sys.exit(main())
